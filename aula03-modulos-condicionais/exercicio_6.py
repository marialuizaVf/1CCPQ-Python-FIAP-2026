v_1= int(input("Digite o primeiro número: "))
v_2= int(input("Digite o segundo número: "))
caractere= input("Digite o operador: ")

if caractere == "+":
    print(v_1 + v_2)
elif caractere == "-":
    print(v_1 - v_2)
elif caractere == "*":
    print(v_1 * v_2)
elif caractere == "/":
    print(v_1 / v_2)